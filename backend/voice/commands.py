PRIORITY = ("stop", "read", "report", "scan", "help", "family", "learn", "alerts", "settings", "habits", "chat", "home", "back")


def parse_command(text: str) -> str | None:
    norm, tokens = prepare_text(text or "")
    if not norm:
        return None
    for intent in PRIORITY:
        if matches_any(norm, tokens, INTENTS[intent]):
            return intent
    return None
